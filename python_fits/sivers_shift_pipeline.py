#!/opt/homebrew/anaconda3/bin/python
"""Regenerate every Sivers-shift output of the paper with ONE mass definition:
    m_N = MassN_Jackknife.h5['PL_-1'] (2903 jackknife samples), multiplied sample by sample into <k_y> = m_N f1T / f1,
    the error being formed at the end by the jackknife; hbar*c = 197.32698 MeV fm; a = 0.11403 fm.
The producers are the analysis notebooks that wrote the paper's figures (identified by md5 of the PDFs), extracted cell by cell
(paper_numbers/nb_to_script.py) and patched ONLY in the mass / hbar*c / path lines (every patch is marked `[sivers_pipeline patch]`).

  python sivers_shift_pipeline.py build              # write the patched scripts to sivers_pipeline/scripts
  python sivers_shift_pipeline.py run MODE [NAME..]  # MODE: orig (unpatched mass, only paths), equiv (array of the constant 0.6228, hbar c=197),
                                                     #       final (PL_-1 jackknife mass, hbar c=197.32698). NAME: ft_xdep ft_xdep_3d zeta_slices extrap fact_shift fact_ratios
Outputs and logs go to sivers_pipeline/out_<MODE>/ ; nothing in the paper is touched by this script."""
import os, sys, json, re, subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
H5 = f"{ROOT}/save_h5_A12B_A2B"
NB2S = f"{HERE}/paper_numbers/nb_to_script.py"
PY = "/opt/homebrew/anaconda3/bin/python"
SCR = f"{HERE}/sivers_pipeline/scripts"
MASSFILE = f"{H5}/TMD_fit/h5data/MassN_Jackknife.h5"
OLDROOT = "/Users/hariprashadravikumar/sivers_TMD_PhD_project"
NEWROOT = ROOT

# name -> (notebook, cells, extra source file instead of a notebook)
PRODUCERS = {
    "ft_xdep":      dict(nb=f"{H5}/SimultaniousFit/SimultaneousFit_A12bA2B_fromh5.ipynb", cells=[0, 1, 2, 3, 4], note="FT_xdep_A2B_A12B_..._b2-9_PL-N.pdf (scalar mass in the original)"),
    "ft_xdep_3d":   dict(nb=f"{H5}/SimultaniousFit/SilumFitAmp_bsq_PL.ipynb", cells=[2, 3, 4, 5, 6], note="FT_xdep_3D_A2B_A12B_..._PL-N.pdf (scalar mass in the original)"),
    "zeta_slices":  dict(nb=f"{H5}/SimultaniousFit/SilumFitAmp_bsq_PL.ipynb", cells=[7], note="SimulFit_Distinct_1_over_PL_*  = zetahat_slices_*.pdf (already PL_-1 jackknife mass)"),
    "extrap":       dict(src=f"{HERE}/paper_numbers/extrapolation_para_level.py", note="extrapolated Sivers curves, 3D, tab:integrals (already PL_-1 jackknife mass, hbar c = 197)"),
    "fact_shift":   dict(src=f"{HERE}/paper_numbers/factorization_sivers_shift.py", note="g(x)h(bT), tab:fact_sivers (already PL_-1 jackknife mass, hbar c = 197)"),
    "fact_ratios":  dict(src=f"{HERE}/paper_numbers/factorization_sivers_ratios.py", note="R_b(x), R_x(b) numbers (already PL_-1 jackknife mass, hbar c = 197)"),
}

LOAD_MASS = ('import h5py as _h5\n'
             'with _h5.File("%s", "r") as _f:   # [sivers_pipeline patch] full P_L=-1 jackknife nucleon mass, one value per jackknife sample\n'
             '    MASSN_JK = _f["PL_-1"][:]\n' % MASSFILE)


def patch(name, src, mode):
    """returns patched source. mode: orig | equiv | final"""
    s = src.replace(OLDROOT, NEWROOT)
    s = s.replace("/Users/hariprashadravikumar/Lattice_QCD_TMD_PhD/sivers_TMD_PhD_project/save_h5_A12B_A2B/SimultaniousFit/FitParams", f"{H5}/SimultaniousFit/FitParams")
    if mode == "orig":
        return s
    hb = "197.0" if mode == "equiv" else "197.32698"
    n_before = s.count("197")
    # hbar*c
    s = re.sub(r"HBARC_MEV_FM\s*=\s*197(?:\.0)?\b", f"HBARC_MEV_FM = {hb}   # [sivers_pipeline patch]", s)
    s = re.sub(r"\(197(?:\.0)? \* 0\.001 / lata\)", f"({hb} * 0.001 / lata)", s)
    s = re.sub(r"\(HBARC_MEV_FM \* 0\.001 / lata\)", f"(HBARC_MEV_FM * 0.001 / lata)", s)
    s = s.replace("hbar*c = 197 MeV fm", f"hbar*c = {hb} MeV fm")
    # mass: scalar -> full jackknife array (only in the producers that used the scalar)
    if name in ("ft_xdep", "ft_xdep_3d"):
        mass_expr = "MASSN_JK" if mode == "final" else "np.full_like(MASSN_JK, 0.6228)"
        s, k1 = re.subn(r"massterm = MassN\s*\*", f"massterm = ({mass_expr}) *", s)   # [sivers_pipeline patch]
        assert k1 >= 1, f"{name}: no scalar massterm line patched"
        s = LOAD_MASS + s
    return s


def build(mode):
    os.makedirs(SCR, exist_ok=True)
    out = {}
    for name, p in PRODUCERS.items():
        if "nb" in p:
            tmp = f"{SCR}/_raw_{name}.py"
            subprocess.run([PY, NB2S, p["nb"], tmp] + [str(c) for c in p["cells"]], check=True, capture_output=True)
            src = open(tmp).read()
        else:
            src = open(p["src"]).read()
        ps = patch(name, src, mode)
        f = f"{SCR}/{name}_{mode}.py"
        open(f, "w").write(f"# generated by sivers_shift_pipeline.py build ({mode}); source: {p.get('nb') or p.get('src')}\n" + ps)
        out[name] = f
    return out


TIMEOUT = {"extrap": 1500}


def run(mode, names):
    scripts = build(mode)
    od = f"{HERE}/sivers_pipeline/out_{mode}"
    os.makedirs(od, exist_ok=True)
    env = dict(os.environ, OMP_NUM_THREADS="1", PYTHONUNBUFFERED="1", MPLBACKEND="Agg")
    for name in names or scripts:
        wd = f"{od}/{name}"
        os.makedirs(wd, exist_ok=True)
        with open(f"{od}/{name}.log", "w") as lg:
            try:
                r = subprocess.run([PY, "-u", scripts[name]], cwd=wd, stdout=lg, stderr=subprocess.STDOUT, env=env, timeout=TIMEOUT.get(name, 5400))
                rc = r.returncode
            except subprocess.TimeoutExpired:
                rc = "TIMEOUT"   # extrap hangs at its final overlay plot after all numbers are printed (see logs)
            lg.write(f"\nFINISHED rc={rc}\n")
        print(name, "rc", rc, flush=True)


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "build":
        for m in ("orig", "equiv", "final"):
            build(m)
        print("built into", SCR)
    elif cmd == "run":
        run(sys.argv[2], sys.argv[3:])
